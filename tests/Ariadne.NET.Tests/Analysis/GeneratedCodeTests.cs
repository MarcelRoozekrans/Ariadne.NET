using Ariadne.NET.Analysis;
using FluentAssertions;
using Microsoft.CodeAnalysis;

namespace Ariadne.NET.Tests.Analysis;

public class GeneratedCodeTests
{
    private static readonly HashSet<SyntaxTree> NoGeneratedTrees = [];

    [Fact]
    public void TreeInGeneratorSet_IsGenerated()
    {
        var compilation = TestCompilation.Create("class Order { }");
        var tree = compilation.SyntaxTrees[0];

        GeneratedCode.IsGeneratedTree(tree, compilation, new HashSet<SyntaxTree> { tree }, CancellationToken.None)
            .Should().BeTrue();
    }

    [Theory]
    [InlineData("// <auto-generated/>\nclass Order { }")]
    [InlineData("/* <auto-generated>\n   by a tool\n</auto-generated> */\nclass Order { }")]
    [InlineData("// <AUTO-GENERATED />\nclass Order { }")]
    [InlineData("// <autogenerated />\nclass Order { }")]
    public void AutoGeneratedHeaderComment_IsGenerated(string source)
    {
        var compilation = TestCompilation.Create(source);

        GeneratedCode.IsGeneratedTree(compilation.SyntaxTrees[0], compilation, NoGeneratedTrees, CancellationToken.None)
            .Should().BeTrue();
    }

    [Theory]
    [InlineData("Foo.g.cs")]
    [InlineData("Foo.g.i.cs")]
    [InlineData("Foo.designer.cs")]
    [InlineData("Foo.generated.cs")]
    [InlineData("Foo.Designer.cs")]
    [InlineData("TemporaryGeneratedFile_036C0B5B.cs")]
    [InlineData("temporarygeneratedfile_abc.cs")]
    public void FileName_IsGenerated(string fileName)
    {
        var compilation = TestCompilation.Create((fileName, "class Order { }"));

        GeneratedCode.IsGeneratedTree(compilation.SyntaxTrees[0], compilation, NoGeneratedTrees, CancellationToken.None)
            .Should().BeTrue();
    }

    [Fact]
    public void AnalyzerConfigGeneratedCodeTrue_IsGenerated()
    {
        var compilation = TestCompilation.Create("class Order { }");
        var tree = compilation.SyntaxTrees[0];
        compilation = compilation.WithOptions(
            compilation.Options.WithSyntaxTreeOptionsProvider(new MarkedGeneratedOptionsProvider(tree)));

        GeneratedCode.IsGeneratedTree(tree, compilation, NoGeneratedTrees, CancellationToken.None)
            .Should().BeTrue();
    }

    [Fact]
    public void TreeInRazorSet_IsNotGenerated()
    {
        var compilation = TestCompilation.Create(("Counter_razor.g.cs", "// <auto-generated/>\nclass Counter { }"));
        var tree = compilation.SyntaxTrees[0];
        var trees = new HashSet<SyntaxTree> { tree };

        GeneratedCode.IsGeneratedTree(tree, compilation, trees, trees, CancellationToken.None)
            .Should().BeFalse();
    }

    [Fact]
    public void TreeInRazorSet_MarkedGeneratedByEditorConfig_IsNotGenerated()
    {
        var compilation = TestCompilation.Create(("Counter_razor.g.cs", "class Counter { }"));
        var tree = compilation.SyntaxTrees[0];
        compilation = compilation.WithOptions(
            compilation.Options.WithSyntaxTreeOptionsProvider(new MarkedGeneratedOptionsProvider(tree)));

        GeneratedCode.IsGeneratedTree(tree, compilation, NoGeneratedTrees, new HashSet<SyntaxTree> { tree }, CancellationToken.None)
            .Should().BeFalse();
    }

    [Fact]
    public void PlainFile_IsNotGenerated()
    {
        var compilation = TestCompilation.Create(("Order.cs", "// An ordinary comment.\nclass Order { }"));

        GeneratedCode.IsGeneratedTree(compilation.SyntaxTrees[0], compilation, NoGeneratedTrees, CancellationToken.None)
            .Should().BeFalse();
    }

    [Fact]
    public void EmptyFilePath_IsNotGeneratedByName()
    {
        var tree = Microsoft.CodeAnalysis.CSharp.CSharpSyntaxTree.ParseText("class Order { }", path: "");
        var compilation = TestCompilation.Create("class Other { }").AddSyntaxTrees(tree);

        GeneratedCode.IsGeneratedTree(tree, compilation, NoGeneratedTrees, CancellationToken.None)
            .Should().BeFalse();
    }

    [Fact]
    public void GeneratedSuffixInDirectoryName_IsNotGenerated()
    {
        var compilation = TestCompilation.Create(("dir.g.cs/Order.cs", "class Order { }"));

        GeneratedCode.IsGeneratedTree(compilation.SyntaxTrees[0], compilation, NoGeneratedTrees, CancellationToken.None)
            .Should().BeFalse();
    }

    [Fact]
    public void ProviderReportingNotGenerated_FallsThroughToFileName()
    {
        var compilation = TestCompilation.Create(("Foo.g.cs", "class Order { }"));
        var tree = compilation.SyntaxTrees[0];
        compilation = compilation.WithOptions(
            compilation.Options.WithSyntaxTreeOptionsProvider(new MarkedGeneratedOptionsProvider(null!)));

        GeneratedCode.IsGeneratedTree(tree, compilation, NoGeneratedTrees, CancellationToken.None)
            .Should().BeTrue();
    }

    [Fact]
    public void AutoGeneratedCommentAfterFirstDeclaration_IsNotGenerated()
    {
        var compilation = TestCompilation.Create("class Order { }\n// <auto-generated/>\nclass Other { }");

        GeneratedCode.IsGeneratedTree(compilation.SyntaxTrees[0], compilation, NoGeneratedTrees, CancellationToken.None)
            .Should().BeFalse();
    }

    [Fact]
    public void GeneratedCodeAttribute_OnType_IsDetected()
    {
        var compilation = TestCompilation.Create(
            "[System.CodeDom.Compiler.GeneratedCode(\"tool\", \"1.0\")] class Order { }");

        GeneratedCode.HasGeneratedCodeAttribute(compilation.GetTypeByMetadataName("Order")!)
            .Should().BeTrue();
    }

    [Fact]
    public void NoAttribute_IsNotDetected()
    {
        var compilation = TestCompilation.Create("class Order { }");

        GeneratedCode.HasGeneratedCodeAttribute(compilation.GetTypeByMetadataName("Order")!)
            .Should().BeFalse();
    }
}
