using System.Collections.Frozen;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using CSharpExtensions = Microsoft.CodeAnalysis.CSharp.CSharpExtensions;

namespace Ariadne.NET.Analysis;

/// <summary>Recognises generated syntax trees and generated types, which the type graph skips.</summary>
internal static class GeneratedCode
{
    private const string GeneratedCodeAttributeMetadataName = "System.CodeDom.Compiler.GeneratedCodeAttribute";
    private const string GeneratedCodeAttributeName = "GeneratedCodeAttribute";
    private const string AutoGeneratedMarker = "<auto-generated";
    private const string AutoGeneratedMarkerWithoutHyphen = "<autogenerated";
    private const string TemporaryFilePrefix = "TemporaryGeneratedFile_";

    private static readonly string[] GeneratedFileSuffixes = [".g.cs", ".g.i.cs", ".designer.cs", ".generated.cs"];

    /// <summary>True when the tree came from a source generator, is marked generated by analyzer config, has a generated file name or starts with an auto-generated header comment.</summary>
    public static bool IsGeneratedTree(
        SyntaxTree tree,
        Compilation compilation,
        IReadOnlySet<SyntaxTree> generatedTrees,
        CancellationToken cancellationToken) =>
        IsGeneratedTree(tree, compilation, generatedTrees, FrozenSet<SyntaxTree>.Empty, cancellationToken);

    /// <summary>
    /// False for a tree of the Razor generator, which is checked as hand-written code; otherwise true when the tree came from a
    /// source generator, is marked generated by analyzer config, has a generated file name or starts with an auto-generated header comment.
    /// </summary>
    public static bool IsGeneratedTree(
        SyntaxTree tree,
        Compilation compilation,
        IReadOnlySet<SyntaxTree> generatedTrees,
        IReadOnlySet<SyntaxTree> razorTrees,
        CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(tree);
        ArgumentNullException.ThrowIfNull(compilation);
        ArgumentNullException.ThrowIfNull(generatedTrees);
        ArgumentNullException.ThrowIfNull(razorTrees);

        if (razorTrees.Contains(tree))
        {
            return false;
        }

        if (generatedTrees.Contains(tree))
        {
            return true;
        }

        var kind = compilation.Options.SyntaxTreeOptionsProvider?.IsGenerated(tree, cancellationToken)
            ?? GeneratedKind.Unknown;
        if (kind == GeneratedKind.MarkedGenerated)
        {
            return true;
        }

        return HasGeneratedFileName(tree.FilePath) || HasAutoGeneratedHeader(tree, cancellationToken);
    }

    /// <summary>True when the type carries <c>System.CodeDom.Compiler.GeneratedCodeAttribute</c>.</summary>
    public static bool HasGeneratedCodeAttribute(INamedTypeSymbol type)
    {
        ArgumentNullException.ThrowIfNull(type);

        foreach (var attribute in type.GetAttributes())
        {
            if (attribute.AttributeClass is { } attributeClass
                && string.Equals(attributeClass.Name, GeneratedCodeAttributeName, StringComparison.Ordinal)
                && string.Equals(
                    attributeClass.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat),
                    GeneratedCodeAttributeMetadataName,
                    StringComparison.Ordinal))
            {
                return true;
            }
        }

        return false;
    }

    private static bool HasGeneratedFileName(string filePath)
    {
        if (string.IsNullOrEmpty(filePath))
        {
            return false;
        }

        var fileName = Path.GetFileName(filePath);
        if (fileName.StartsWith(TemporaryFilePrefix, StringComparison.OrdinalIgnoreCase))
        {
            return true;
        }

        foreach (var suffix in GeneratedFileSuffixes)
        {
            if (fileName.EndsWith(suffix, StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }
        }

        return false;
    }

    private static bool HasAutoGeneratedHeader(SyntaxTree tree, CancellationToken cancellationToken)
    {
        var firstToken = tree.GetRoot(cancellationToken).GetFirstToken(includeZeroWidth: true);
        foreach (var trivia in firstToken.LeadingTrivia)
        {
            var kind = CSharpExtensions.Kind(trivia);
            if (kind is SyntaxKind.SingleLineCommentTrivia or SyntaxKind.MultiLineCommentTrivia)
            {
                var text = trivia.ToString();
                if (text.Contains(AutoGeneratedMarker, StringComparison.OrdinalIgnoreCase)
                    || text.Contains(AutoGeneratedMarkerWithoutHyphen, StringComparison.OrdinalIgnoreCase))
                {
                    return true;
                }
            }
        }

        return false;
    }
}
